public class Calc {
    // Final constant for calculator identification
    public static final String TYPE = "Standard Calculator";

    // Access control: Public methods for basic arithmetic
    public double add(double a, double b) {
        return a + b;
    }

    public double subtract(double a, double b) {
        return a - b;
    }

    public double multiply(double a, double b) {
        return a * b;
    }

    public double divide(double a, double b) {
        if (b == 0) {
            throw new ArithmeticException("Cannot divide by zero.");
        }
        return a / b;
    }
}